// Builds src/lib/banlist.json for the username and nickname filter. Run: npm run banlist
// Needs the claude-games repo next to this one (or KIT_DIR) for its word lists and dictionary.
// Sources: LDNOOBW English (naughty-words, CC BY 4.0), badwords-list (MIT), the Kit's slur list.
// Two tiers:
//   inside: banned anywhere in the name (only words that never appear inside a normal English word)
//   word:   banned as a whole word, or at the start/end of a run of letters (4+ letters)
const fs = require('fs');
const path = require('path');
const kit = path.resolve(process.env.KIT_DIR ?? path.join(__dirname, '../../claude-games'), 'kit/words');
const lines = (f) => fs.readFileSync(path.join(kit, f), 'utf8').split('\n').map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith('#'));

const dictDir = path.join(kit, 'data/large');
const dict = fs.readdirSync(dictDir).flatMap((f) => fs.readFileSync(path.join(dictDir, f), 'utf8').split('\n')).map((w) => w.trim()).filter(Boolean);

// Mild words that are fine in a username.
const MILD = new Set(['god', 'gods', 'hell', 'damn', 'crap', 'lust', 'pawn', 'knob', 'nob', 'xx', 'bum', 'suck', 'sucks', 'homo', 'pron', 'teez', 'cipa', 'cox', 'dink', 'sexo', 'mofo', 'hoar', 'pube', 'quim', 'feck', 'poop', 'scat', 'muff', 'wang', 'shag', 'turd', 'butt', 'nude', 'smut', 'boob', 'anus']);
// Turd, butt, boob, anus, nude, smut stay banned as whole words below.
const BACK = ['turd', 'butt', 'boob', 'boobs', 'anus', 'nude', 'nudes', 'smut'];

const allow = new Set(lines('allowlist.txt'));
const base = [...require('naughty-words').en, ...require('badwords-list').array, ...lines('blocklist-extra.txt'), ...BACK]
  .map((w) => w.toLowerCase().trim().replace(/\s+/g, ''))
  .filter((w) => /^[a-z]+$/.test(w) && w.length >= 3 && (!MILD.has(w) || BACK.includes(w)));
const ends = ['', 's', 'es', 'ed', 'er', 'ers', 'ing', 'y'];
const word = [...new Set(base.flatMap((w) => ends.map((e) => w + e)))].filter((w) => !allow.has(w)).sort();

// Slurs and hard words banned anywhere even though a rare English word contains them (snigger, shitake).
const FORCE = ['nigg', 'nigga', 'nigger', 'faggot', 'fagot', 'slut', 'whore', 'porn', 'bitch', 'pussy', 'hitler', 'kkk', 'nazi', 'cunt', 'fuck', 'fuk', 'fck', 'kike', 'chink', 'wetback', 'towelhead', 'raghead', 'tranny', 'pedo', 'pedophil', 'paedophil', 'molest'];
// A word may go in the "inside" tier only if no dictionary word contains it (other than its own forms).
// Phrases from the public lists that are fine as names.
const NOT_INSIDE = new Set(['bigblack', 'barenaked', 'bastinado', 'babeland', 'birdlock', 'bimbos', 'bareback']);
const words = new Set(base);
const inside = [...new Set(base)].filter((w) => w.length >= 4 && !NOT_INSIDE.has(w)).filter((w) => {
  const hits = dict.filter((d) => d.includes(w) && !d.startsWith(w) && !words.has(d));
  const hitsStart = dict.filter((d) => d.startsWith(w) && d !== w && !words.has(d) && !ends.some((e) => d === w + e));
  return hits.length === 0 && hitsStart.length === 0;
}).concat(FORCE).filter((w, i, a) => a.indexOf(w) === i).sort();

// Real words that start or end with a banned word (4+ letters) but are fine: peacock, cocktail, dickens.
const word4 = word.filter((w) => w.length >= 4);
const wordSet = new Set(word);
const safe = dict.filter((d) => !wordSet.has(d) && word4.some((w) => d !== w && (d.startsWith(w) || d.endsWith(w)))).sort();

// Names people could use to pose as staff, or that the site uses itself.
const reserved = ['admin', 'administrator', 'mod', 'moderator', 'staff', 'support', 'official', 'system', 'root', 'secondmonitor', 'secondmonitorgames', 'smg', 'ironfox', 'ironfoxgames', 'claude', 'anthropic', 'guest', 'player', 'anonymous', 'null', 'undefined', 'everyone'];

const out = { safe, note: 'Generated by scripts/banlist (claude-games word lists): LDNOOBW English (CC BY 4.0), badwords-list (MIT), Kit slur list. Edit src/lib/banlist-extra.ts for hand changes.', inside, word, reserved };
fs.writeFileSync(path.join(__dirname, '../src/lib/banlist.json'), JSON.stringify(out));
console.log('safe', safe.length, 'inside', inside.length, 'word', word.length);
console.log('inside sample', inside.slice(0, 60).join(' '));
